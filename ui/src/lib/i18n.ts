const DICTS: Record<Locale, Dict> = { vi, en, zh };

export type Params = Record<string, string | number>;
export type T = (key: MessageKey, params?: Params) => string;

export function isLocale(x: unknown): x is Locale {
  return typeof x === "string" && (LOCALES as readonly string[]).includes(x);
}

export function makeT(locale: Locale): T {
  const d = DICTS[locale];
  return (key, params) => {
    let s = d[key] ?? vi[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Error thrown by server code with a translatable message. */
export class I18nError extends Error {
  constructor(public key: MessageKey, public params?: Params) {
    super(key);
  }
}

export function formatDate(iso: string, locale: Locale, dateOnly = false): string {
  const d = new Date(iso);
  if (isNaN(d.getTime())) return iso;
  const intl = LOCALE_META[locale].intl;
  return dateOnly ? d.toLocaleDateString(intl) : d.toLocaleString(intl);
}

export function formatNumber(n: number, locale: Locale): string {
  return n.toLocaleString(LOCALE_META[locale].intl);
}

/** Picks the best supported locale from an Accept-Language header. */
export function negotiate(acceptLanguage: string | null): Locale {
  for (const part of (acceptLanguage ?? "").split(",")) {
    const tag = part.split(";")[0].trim().toLowerCase();
    if (tag.startsWith("vi")) return "vi";
    if (tag.startsWith("zh")) return "zh";
    if (tag.startsWith("en")) return "en";
  }
  return DEFAULT_LOCALE;
}

export const THEMES = ["light", "dark", "system"] as const;
export type Theme = (typeof THEMES)[number];
export function isTheme(x: unknown): x is Theme {
  return typeof x === "string" && (THEMES as readonly string[]).includes(x);
}
